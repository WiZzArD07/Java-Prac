public class char_datatype {
    public static void main(String[] args) {
        char ch = 'A';
        int x = ch;
        System.out.println(x);

        char aryan = 'a';
        int y = (int)aryan;
        System.out.println(y);

        char c = '3';
        System.out.println((int)c);

        char a = 'c';
        System.out.println(a*a);

        int e = 65;
        char f = (char)e;
        System.out.println(f);
    }
}
