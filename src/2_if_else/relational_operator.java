public class relational_operator {
    public static void main(String[] args) {
        System.out.println(5>6);
        System.out.println(5<6);
        System.out.println(5>=6);
        System.out.println(5<=6);
        System.out.println(5==6);
        System.out.println(5!=6);
        System.out.println(6*7 == 42);

        boolean x = true;
        System.out.println(x);

        boolean y = false;
        System.out.println(y);

        boolean z = 5>6;
        System.out.println(z); 


    }
}
 